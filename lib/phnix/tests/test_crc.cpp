// CRC tests use complete, CRC-valid frames captured from the reference unit
// (Protocol.md §5 and Appendix A). If the CRC routine is correct, every
// captured frame must self-validate, and recomputing the CRC over the payload
// must reproduce the captured trailing two bytes.
#include "phnix/crc.h"
#include "test_framework.h"

using namespace phnix;

// All frames are full captures including their (low,high) CRC bytes.
static const std::vector<std::vector<uint8_t>> kCapturedFrames = {
    {0x63, 0x03, 0x00, 0x07, 0x00, 0x2D, 0x3C, 0x54},               // read all
    {0x63, 0x10, 0x03, 0xF3, 0x00, 0x01, 0x02, 0x00, 0x00, 0x30, 0xF1},  // off
    {0x63, 0x10, 0x03, 0xF3, 0x00, 0x01, 0x02, 0x00, 0x01, 0xF1, 0x31},  // on
    {0x63, 0x10, 0x03, 0xF4, 0x00, 0x02, 0x04, 0x00, 0x00, 0x00, 0x00, 0x1C, 0x51},  // cool
    {0x63, 0x10, 0x03, 0xF4, 0x00, 0x02, 0x04, 0x00, 0x01, 0x00, 0x88, 0x4D, 0xF7},  // heat
    {0x63, 0x10, 0x03, 0xF4, 0x00, 0x02, 0x04, 0x00, 0x02, 0x00, 0x8C, 0xBC, 0x34},  // auto
    {0x63, 0x10, 0x04, 0x1B, 0x00, 0x01, 0x02, 0x00, 0x96, 0xD1, 0x77},  // cool target 15.0
    {0x63, 0x10, 0x04, 0x2C, 0x00, 0x01, 0x02, 0x01, 0x40, 0x55, 0x3E},  // auto target 32.0
    {0x63, 0x10, 0x04, 0x25, 0x00, 0x01, 0x02, 0x00, 0x01, 0x94, 0x07},  // defrost eco
    {0x63, 0x10, 0x03, 0xFF, 0x00, 0x01, 0x02, 0x00, 0x02, 0xB1, 0xFC},  // mode type heat-only
    {0x63, 0x10, 0x04, 0x0D, 0x00, 0x01, 0x02, 0x00, 0x01, 0x92, 0x2F},  // pump stop
};

TEST(crc_captured_frames_self_validate) {
  for (const auto &f : kCapturedFrames) CHECK(check_crc(f));
}

TEST(crc_recompute_matches_trailing_bytes) {
  for (const auto &f : kCapturedFrames) {
    uint16_t crc = modbus_crc16(f.data(), f.size() - 2);
    CHECK_EQ(static_cast<uint8_t>(crc & 0xFF), f[f.size() - 2]);
    CHECK_EQ(static_cast<uint8_t>((crc >> 8) & 0xFF), f[f.size() - 1]);
  }
}

TEST(crc_append_roundtrip) {
  std::vector<uint8_t> payload = {0x63, 0x03, 0x00, 0x07, 0x00, 0x2D};
  append_crc(payload);
  CHECK(check_crc(payload));
  CHECK_EQ(payload[payload.size() - 2], 0x3C);
  CHECK_EQ(payload[payload.size() - 1], 0x54);
}

TEST(crc_detects_corruption) {
  std::vector<uint8_t> f = kCapturedFrames[2];  // power on
  f[8] ^= 0xFF;                                 // flip a payload byte
  CHECK(!check_crc(f));
}

TEST(crc_rejects_too_short) {
  std::vector<uint8_t> f = {0x01, 0x02};
  CHECK(!check_crc(f));
}
