// Golden frames: complete block notifications captured verbatim from the
// reference unit via the shadow-mode harness (see SHADOW.md). Unlike the
// synthesised frames in test_decode.cpp, these pin the real wire format —
// real slave address, real register layout, real CRC. parse_block() asserting
// `valid` here is itself a test: it proves the library accepts genuine
// hardware frames (CRC + length), which is exactly what shadow mode confirmed
// on-device.
#include "phnix/decode.h"
#include "test_framework.h"

using namespace phnix;

